const {describe,it,beforeEach,after}=require('node:test')
const assert=require('node:assert/strict')
const {randomUUID}=require('node:crypto')
const {createStockReceivingHandlers}=require('./stockReceiving')
const {createFinanceOperations}=require('./financeOperations')
const {createRegisterHandlers}=require('./registerPayments')
const {createVendorOpeningHandlers}=require('./vendorOpening')

describe('approved stock/vendor revision — isolated transactions', {skip:process.env.RUN_STOCK_VENDOR_TESTS!=='true'},()=>{
 if(process.env.FIRESTORE_EMULATOR_HOST!=='127.0.0.1:8080')throw Error('Exact loopback emulator required')
 const {initializeApp,deleteApp}=require('firebase-admin/app'),{getFirestore}=require('firebase-admin/firestore')
 const project='demo-stock-vendor-revision',app=initializeApp({projectId:project},'stock-vendor-revision'),db=getFirestore(app),base='posSandboxes/test'
 const receiving=createStockReceivingHandlers(db,()=> '2026-10-29T09:00:00.000Z'),ops=createFinanceOperations(db,()=>Date.parse('2026-10-29T09:00:00Z')),register=createRegisterHandlers(ops),opening=createVendorOpeningHandlers(ops,register)
 const req=(data,uid='owner')=>({auth:{uid,token:{auth_time:42}},data:{operationId:randomUUID(),...data}})
 const read=async path=>(await db.doc(path).get()).data()
 const draft=(extra={})=>({id:randomUUID(),expectedRevision:0,vendorId:'v',invoiceNumber:'INV-1',invoiceDate:'2026-10-29',receiptDate:'2026-10-29',invoiceTotalPaise:999999,pricingMode:'received-stock',lines:[{productId:'p',barcode:'007',productName:'Synthetic item',category:'Fixture',quantity:2,unitCostPaise:8000,mrpPaise:10000,sellingPricePaise:10000,expectedRevision:1}],...extra})
 async function post(extra={}){const saved=await receiving.saveDraft(req(draft(extra)));const intent=req({id:saved.id,expectedRevision:saved.revision});const result=await receiving.submit(intent);return {saved,result,intent,purchaseId:result.purchaseId}}
 beforeEach(async()=>{
  assert.equal((await fetch(`http://127.0.0.1:8080/emulator/v1/projects/${project}/databases/(default)/documents`,{method:'DELETE'})).ok,true)
  const b=db.batch();for(const [uid,role]of[['owner','owner'],['manager','manager'],['billing','billing'],['disabled','owner']])b.set(db.doc('users/'+uid),{name:'Synthetic '+uid,role,disabled:uid==='disabled',approvalStatus:'approved'})
  b.set(db.doc('appMetadata/vendorLedgerV2Config'),{enabled:true,activationDate:'2026-01-01'})
  b.set(db.doc('vendorsV2/v'),{id:'v',canonicalName:'Synthetic vendor',active:true,openingBalancePaise:0,revision:1,aliases:[],suppliedBrands:[]})
  b.set(db.doc('vendorAccountStatesV2/v'),{id:'v',vendorId:'v',outstandingPaise:0,vendorCreditPaise:0,revision:1})
  b.set(db.doc(base+'/products/p'),{id:'p',barcode:'007',name:'Synthetic item',category:'Fixture',active:true,currentQuantity:5,sellingPricePaise:10000,sourceValues:{'Printed MRP':'100'},revision:1})
  await b.commit()
 })
 after(()=>deleteApp(app))
 it('recomputes the payable without trusting the browser total or an omitted pricing mode',async()=>{
  const r=await post();assert.equal(r.saved.invoiceTotalPaise,16000);assert.equal(r.result.totalPaise,16000)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,16000)
  assert.equal((await read(base+'/products/p')).currentQuantity,7)
  assert.deepEqual(await receiving.submit(r.intent),r.result)
  assert.equal((await db.collection('purchasesV2').get()).size,1)
  await assert.rejects(receiving.saveDraft(req(draft({pricingMode:undefined,invoiceTotalPaise:999999,invoiceNumber:'OLD-CLIENT'}))),/Reload Receive Stock/)
  const oldClient=await receiving.saveDraft(req(draft({pricingMode:undefined,invoiceTotalPaise:16000,invoiceNumber:'OLD-MATCHING'})));assert.equal(oldClient.invoiceTotalPaise,16000)
 })
 it('saves an incomplete zero-value draft without posting stock or payable',async()=>{
  const input=draft();input.lines[0].quantity=0;input.lines[0].unitCostPaise=0
  const saved=await receiving.saveDraft(req(input));assert.equal(saved.invoiceTotalPaise,0)
  assert.equal((await read(base+'/products/p')).currentQuantity,5)
  await assert.rejects(receiving.submit(req({id:saved.id,expectedRevision:1})))
  assert.equal((await db.collection('purchasesV2').get()).size,0)
 })
 it('keeps awaited credit pending, then applies a received note exactly once with audit evidence',async()=>{
  const r=await post({shortage:{state:'pending',originalInvoiceTotalPaise:20000}})
  assert.equal(r.result.totalPaise,20000)
  const confirm=req({id:r.saved.id,expectedRevision:2,creditNoteNumber:'CN-1',creditNoteDate:'2026-10-29'})
  const next=await receiving.confirmCreditNote(confirm);assert.equal(next.invoiceTotalPaise,16000)
  assert.equal(next.shortage.originalInvoiceTotalPaise,20000)
  assert.equal((await read('invoiceStatesV2/'+r.purchaseId)).openAmountPaise,16000)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,16000)
  assert.deepEqual(await receiving.confirmCreditNote(confirm),next)
  await assert.rejects(receiving.confirmCreditNote(req({...confirm.data,operationId:randomUUID()})),/no pending/)
  const ledger=(await db.collection('vendorLedgerEntriesV2').get()).docs.map(d=>d.data())
  assert.equal(ledger.reduce((sum,row)=>sum+row.signedAmountPaise,0),16000)
  assert.equal((await read(base+'/products/p')).currentQuantity,7)
 })
 it('already-received credit is included in the net invoice, not deducted a second time',async()=>{
  const r=await post({shortage:{state:'received',originalInvoiceTotalPaise:20000,creditNoteNumber:'CN-1',creditNoteDate:'2026-10-29'}})
  assert.equal(r.result.totalPaise,16000);assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,16000)
  assert.equal((await db.collection('vendorCreditNoteReservationsV2').get()).size,1)
  await assert.rejects(receiving.confirmCreditNote(req({id:r.saved.id,expectedRevision:2,creditNoteNumber:'CN-1',creditNoteDate:'2026-10-29'})),/no pending/)
 })
 it('rejects a reused credit note on a different invoice without adding stock or payable',async()=>{
  await post({shortage:{state:'received',originalInvoiceTotalPaise:20000,creditNoteNumber:'CN-1',creditNoteDate:'2026-10-29'}})
  const input=draft({invoiceNumber:'INV-2',shortage:{state:'received',originalInvoiceTotalPaise:20000,creditNoteNumber:'cn-1',creditNoteDate:'2026-10-29'}});input.lines[0].expectedRevision=2
  const saved=await receiving.saveDraft(req(input));await assert.rejects(receiving.submit(req({id:saved.id,expectedRevision:1})),/already linked/)
  assert.equal((await read(base+'/products/p')).currentQuantity,7);assert.equal((await db.collection('purchasesV2').get()).size,1)
 })
 it('concurrent confirmations cannot use one credit note on two invoices',async()=>{
  const a=await post({shortage:{state:'pending',originalInvoiceTotalPaise:20000}})
  const input=draft({invoiceNumber:'INV-2',shortage:{state:'pending',originalInvoiceTotalPaise:20000}});input.lines[0].expectedRevision=2
  const saved=await receiving.saveDraft(req(input));await receiving.submit(req({id:saved.id,expectedRevision:1}))
  const results=await Promise.allSettled([a.saved.id,saved.id].map(id=>receiving.confirmCreditNote(req({id,expectedRevision:2,creditNoteNumber:'CN-RACE',creditNoteDate:'2026-10-29'}))))
  assert.equal(results.filter(result=>result.status==='fulfilled').length,1)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,36000)
  assert.equal((await db.collection('vendorCreditNoteReservationsV2').get()).size,1)
 })
 it('creates vendor credit when the invoice was paid before the shortage note arrived',async()=>{
  const r=await post({shortage:{state:'pending',originalInvoiceTotalPaise:20000}})
  await register.settlement(req({id:'payment',vendorId:'v',invoiceId:r.purchaseId,date:'2026-10-29',amountPaise:18000,mode:'bank-transfer',notes:'Synthetic payment'}))
  const originalPayment=await read('vendorSettlementsV2/payment')
  await receiving.confirmCreditNote(req({id:r.saved.id,expectedRevision:2,creditNoteNumber:'CN-LATE',creditNoteDate:'2026-10-29'}))
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,0)
  assert.equal((await read('vendorAccountStatesV2/v')).vendorCreditPaise,2000)
  assert.equal((await read('invoiceStatesV2/'+r.purchaseId)).openAmountPaise,0)
  assert.deepEqual(await read('vendorSettlementsV2/payment'),originalPayment)
 })
 it('blocks credit against reserved cheques and stale/unauthorized confirmation',async()=>{
  const r=await post({shortage:{state:'pending',originalInvoiceTotalPaise:20000}})
  const data={id:r.saved.id,expectedRevision:2,creditNoteNumber:'CN-1',creditNoteDate:'2026-10-29'}
  for(const uid of['manager','billing','disabled'])await assert.rejects(receiving.confirmCreditNote(req(data,uid)))
  await assert.rejects(receiving.confirmCreditNote(req({...data,expectedRevision:1})))
  await db.doc('invoiceStatesV2/'+r.purchaseId).update({reservedAmountPaise:18000})
  await assert.rejects(receiving.confirmCreditNote(req(data)),/pending cheque/)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,20000)
  assert.equal((await db.collection('vendorCreditNoteReservationsV2').get()).size,0)
 })
 it('rejects second deliveries/duplicate invoice numbers and legacy drafts needing review',async()=>{
  await post();const input=draft({invoiceNumber:' inv-1 '});input.lines[0].expectedRevision=2
  const saved=await receiving.saveDraft(req(input));await assert.rejects(receiving.submit(req({id:saved.id,expectedRevision:1})),/already recorded/)
  assert.equal((await read(base+'/products/p')).currentQuantity,7)
  const legacy=draft();delete legacy.pricingMode;await db.doc(base+'/goodsReceipts/legacy-draft').set({...legacy,id:'legacy-draft',status:'draft',revision:1})
  await assert.rejects(receiving.submit(req({id:'legacy-draft',expectedRevision:1})),/older draft/)
 })
 it('opening correction posts only its delta, replays safely and preserves unrelated history',async()=>{
  await db.doc('payments/history').set({partyName:'Real party',amount:123})
  const intent=req({vendorId:'v',expectedVendorRevision:1,expectedAccountRevision:1,openingBalancePaise:15000,reason:'Statement verified'})
  const result=await opening.correct(intent);assert.equal(result.differencePaise,15000)
  assert.deepEqual(await opening.correct(intent),result)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,15000)
  assert.deepEqual(await read('payments/history'),{partyName:'Real party',amount:123})
  assert.equal((await db.collection('vendorLedgerEntriesV2').get()).size,1)
 })
 it('opening reductions handle prior payments as vendor credit without rewriting them',async()=>{
  await db.doc('vendorsV2/v').update({openingBalancePaise:10000})
  await db.doc('vendorAccountStatesV2/v').update({outstandingPaise:2000})
  await db.doc('vendorLedgerEntriesV2/original').set({vendorId:'v',eventType:'opening-balance',signedAmountPaise:10000})
  await db.doc('vendorSettlementsV2/old-payment').set({id:'old-payment',vendorId:'v',amountPaise:8000})
  await opening.correct(req({vendorId:'v',expectedVendorRevision:1,expectedAccountRevision:1,openingBalancePaise:5000,reason:'Correct statement opening'}))
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,0);assert.equal((await read('vendorAccountStatesV2/v')).vendorCreditPaise,3000)
  assert.equal((await read('vendorLedgerEntriesV2/original')).signedAmountPaise,10000)
  assert.equal((await read('vendorSettlementsV2/old-payment')).amountPaise,8000)
 })
 it('opening authority, expected revisions and concurrent submissions are enforced server-side',async()=>{
  const intent={vendorId:'v',expectedVendorRevision:1,expectedAccountRevision:1,openingBalancePaise:5000,reason:'Verified'}
  for(const uid of['manager','billing','disabled'])await assert.rejects(opening.correct(req(intent,uid)))
  await assert.rejects(opening.correct(req({...intent,reason:''})))
  const results=await Promise.allSettled([opening.correct(req(intent)),opening.correct(req({...intent,openingBalancePaise:7000}))])
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1)
  assert.equal((await db.collection('vendorLedgerEntriesV2').get()).size,1)
  assert.equal((await read('vendorsV2/v')).revision,2)
 })
 it('opening reductions preserve payable reserved by account-level pending cheques',async()=>{
  await db.doc('vendorsV2/v').update({openingBalancePaise:10000})
  await db.doc('vendorAccountStatesV2/v').update({outstandingPaise:10000})
  await db.doc('chequesV2/C1').set({vendorId:'v',status:'issued',amountPaise:9000,trackingOnly:false})
  await assert.rejects(opening.correct(req({vendorId:'v',expectedVendorRevision:1,expectedAccountRevision:1,openingBalancePaise:5000,reason:'Verified reduction'})),/Pending vendor cheques/)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,10000)
  assert.equal((await db.collection('vendorLedgerEntriesV2').get()).size,0)
 })
 it('a shortage note cannot overcommit an unallocated pending vendor cheque',async()=>{
  const r=await post({shortage:{state:'pending',originalInvoiceTotalPaise:20000}})
  await db.doc('chequesV2/C2').set({vendorId:'v',status:'presented',amountPaise:18000,trackingOnly:false})
  await assert.rejects(receiving.confirmCreditNote(req({id:r.saved.id,expectedRevision:2,creditNoteNumber:'CN-ACCOUNT',creditNoteDate:'2026-10-29'})),/Pending vendor cheques/)
  assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise,20000)
  assert.equal((await db.collection('vendorCreditNoteReservationsV2').get()).size,0)
 })
 it('malformed shortage amounts, future notes and overflow fail without financial writes',async()=>{
  await assert.rejects(receiving.saveDraft(req(draft({shortage:{state:'pending',originalInvoiceTotalPaise:100}}))))
  const input=draft();input.lines[0].quantity=Number.MAX_SAFE_INTEGER
  await assert.rejects(receiving.saveDraft(req(input)))
  const saved=await receiving.saveDraft(req(draft({shortage:{state:'received',originalInvoiceTotalPaise:20000,creditNoteNumber:'FUTURE',creditNoteDate:'2026-11-01'}})))
  await assert.rejects(receiving.submit(req({id:saved.id,expectedRevision:1})),/between invoice date and today/)
  assert.equal((await db.collection('purchasesV2').get()).size,0)
 })
})
