const { describe, it, beforeEach, after } = require('node:test')
const assert = require('node:assert/strict')
const { initializeApp, deleteApp } = require('firebase-admin/app')
const { getFirestore } = require('firebase-admin/firestore')
const { createStockPriceHandlers } = require('./stockPrices')

describe('stock price server posting in isolated emulator', { skip: !process.env.FIRESTORE_EMULATOR_HOST }, () => {
  if (!/^(127\.0\.0\.1|localhost):\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST)) throw new Error('Only a loopback Firestore emulator is permitted.')
  const app = initializeApp({ projectId: 'demo-stock-prices' }, 'stock-prices-test')
  const db = getFirestore(app)
  const handlers = createStockPriceHandlers(db, () => '2026-10-12T10:00:00.000Z')
  const path = 'posSandboxes/test'
  const productRef = db.doc(`${path}/products/qa-product`)
  const initial = { barcode: '00012', name: 'Test Product', category: 'Test', brand: 'Test', vendor: 'Test', searchName: 'test product', sellingPricePaise: 900, currentQuantity: 12, revision: 1, createdAt: '2026-10-01T00:00:00.000Z', createdByUid: 'owner', sourceValues: { 'Printed MRP': '10.00', 'Opening Quantity': '12', evidence: 'preserve' } }
  const draft = (extra = {}) => ({ operationId: 'stock-price-first', productId: 'qa-product', expectedRevision: 1, mrpPaise: 1200, sellingPricePaise: 1000, reason: 'Wrong printed price', ...extra })
  const request = (uid = 'billing', extra = {}) => ({ auth: { uid }, data: draft(extra) })

  beforeEach(async () => {
    for (const name of ['products', 'stockPriceChanges', 'stockMovements', 'productCosts', 'bills', 'goodsReceipts']) await db.recursiveDelete(db.collection(`${path}/${name}`))
    for (const [uid, role] of [['owner', 'owner'], ['manager', 'manager'], ['billing', 'billing'], ['disabled', 'billing'], ['outsider', 'viewer']]) await db.doc(`users/${uid}`).set({ role, name: `Server ${uid}`, disabled: uid === 'disabled' })
    await productRef.set(initial)
    await db.doc(`${path}/productCosts/qa-product`).set({ costPaise: 500 })
    await db.doc(`${path}/bills/history`).set({ sellingPricePaise: 900 })
    await db.doc(`${path}/goodsReceipts/history`).set({ mrpPaise: 1000 })
  })
  after(async () => { await deleteApp(app) })

  for (const uid of ['owner', 'manager', 'billing']) it(`${uid} applies prices and audit together without changing quantity or historical finance`, async () => {
    const record = await handlers.change(request(uid, { actorName: 'Spoofed', actorUid: 'owner' }))
    const product = (await productRef.get()).data()
    assert.equal(product.sourceValues['Printed MRP'], '12.00')
    assert.equal(product.sellingPricePaise, 1000)
    assert.equal(product.currentQuantity, 12)
    assert.equal(product.revision, 2)
    assert.equal(product.sourceValues.evidence, 'preserve')
    assert.equal(product.lastPriceEdit.byName, `Server ${uid}`)
    assert.equal(record.actorUid, uid)
    assert.equal(record.reviewStatus, 'pending')
    assert.deepEqual(record.before, { mrpPaise: 1000, sellingPricePaise: 900 })
    assert.equal((await db.doc(`${path}/stockPriceChanges/${record.id}`).get()).data().actorName, `Server ${uid}`)
    const movement = (await db.doc(`${path}/stockMovements/${record.id}`).get()).data()
    assert.equal(movement.quantityDelta, 0)
    assert.equal(movement.beforeSellingPricePaise, 900)
    assert.equal(movement.afterMrpPaise, 1200)
    assert.deepEqual((await db.doc(`${path}/productCosts/qa-product`).get()).data(), { costPaise: 500 })
    assert.deepEqual((await db.doc(`${path}/bills/history`).get()).data(), { sellingPricePaise: 900 })
    assert.deepEqual((await db.doc(`${path}/goodsReceipts/history`).get()).data(), { mrpPaise: 1000 })
  })
  it('requires an authenticated active staff account', async () => {
    await assert.rejects(handlers.change({ data: draft() }), { code: 'unauthenticated' })
    for (const uid of ['disabled', 'outsider', 'missing']) await assert.rejects(handlers.change(request(uid)), { code: 'permission-denied' })
    assert.equal((await productRef.get()).data().revision, 1)
  })
  it('rejects invalid money, missing reasons, invalid ids and no-op edits', async () => {
    for (const extra of [{ mrpPaise: -1 }, { mrpPaise: 1.5 }, { sellingPricePaise: Number.MAX_SAFE_INTEGER + 1 }, { sellingPricePaise: '1000' }, { reason: '' }, { expectedRevision: 0 }, { productId: '../outside' }]) await assert.rejects(handlers.change(request('billing', extra)), { code: 'invalid-argument' })
    await assert.rejects(handlers.change(request('billing', { mrpPaise: 1000, sellingPricePaise: 900 })), { code: 'failed-precondition' })
    assert.equal((await db.collection(`${path}/stockPriceChanges`).get()).size, 0)
  })
  it('rejects stale edits and preserves both prices', async () => {
    await productRef.update({ revision: 2 })
    await assert.rejects(handlers.change(request()), { code: 'failed-precondition' })
    assert.equal((await productRef.get()).data().sellingPricePaise, 900)
    assert.equal((await db.collection(`${path}/stockMovements`).get()).size, 0)
  })
  it('retries the same operation without resetting later changes and rejects changed evidence', async () => {
    await handlers.change(request())
    await handlers.change(request('manager', { operationId: 'stock-price-second', expectedRevision: 2, mrpPaise: 1500, sellingPricePaise: 1400 }))
    await handlers.change(request())
    assert.equal((await productRef.get()).data().sellingPricePaise, 1400)
    assert.equal((await db.collection(`${path}/stockPriceChanges`).get()).size, 2)
    await assert.rejects(handlers.change(request('billing', { sellingPricePaise: 1100 })), { code: 'already-exists' })
    await assert.rejects(handlers.change(request('manager')), { code: 'already-exists' })
  })
  it('serializes simultaneous staff edits; only one revision and audit can succeed', async () => {
    const results = await Promise.allSettled([handlers.change(request()), handlers.change(request('manager', { operationId: 'stock-price-other' }))])
    assert.equal(results.filter((result) => result.status === 'fulfilled').length, 1)
    assert.equal((await productRef.get()).data().revision, 2)
    assert.equal((await db.collection(`${path}/stockPriceChanges`).get()).size, 1)
    assert.equal((await db.collection(`${path}/stockMovements`).get()).size, 1)
  })
  it('only the owner acknowledges changes; review does not reapply or undo newer prices', async () => {
    await handlers.change(request())
    for (const uid of ['billing', 'manager', 'disabled']) await assert.rejects(handlers.review({ auth: { uid }, data: { id: 'stock-price-first' } }), { code: 'permission-denied' })
    await handlers.change(request('manager', { operationId: 'stock-price-second', expectedRevision: 2, mrpPaise: 1500, sellingPricePaise: 1400 }))
    await handlers.review({ auth: { uid: 'owner' }, data: { id: 'stock-price-first' } })
    await handlers.review({ auth: { uid: 'owner' }, data: { id: 'stock-price-first' } })
    const change = (await db.doc(`${path}/stockPriceChanges/stock-price-first`).get()).data()
    assert.equal(change.reviewStatus, 'reviewed')
    assert.equal(change.reviewedByName, 'Server owner')
    assert.equal((await productRef.get()).data().sellingPricePaise, 1400)
    assert.equal((await productRef.get()).data().revision, 3)
  })
  it('rejects selling above MRP and missing MRP without any writes', async () => {
    for (const extra of [{ mrpPaise: 999, sellingPricePaise: 1000 }, { mrpPaise: null, sellingPricePaise: 0 }]) await assert.rejects(handlers.change(request('billing', extra)), { code: 'invalid-argument' })
    assert.deepEqual((await productRef.get()).data(), initial)
    assert.equal((await db.collection(`${path}/stockPriceChanges`).get()).size, 0)
    assert.equal((await db.collection(`${path}/stockMovements`).get()).size, 0)
  })
  it('allows selling equal to MRP, including zero prices', async () => {
    await handlers.change(request('billing', { mrpPaise: 1200, sellingPricePaise: 1200 }))
    await handlers.change(request('billing', { operationId: 'stock-price-zero', expectedRevision: 2, mrpPaise: 0, sellingPricePaise: 0 }))
    assert.equal((await productRef.get()).data().sourceValues['Printed MRP'], '0.00')
    assert.equal((await productRef.get()).data().sellingPricePaise, 0)
  })
})
