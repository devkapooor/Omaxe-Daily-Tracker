const { describe, it, beforeEach, after } = require('node:test')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { createFinanceOperations } = require('./financeOperations')
const { createRegisterHandlers } = require('./registerPayments')
const { createVendorDecisionHandlers } = require('./vendorFinanceDecisions')
const { createStockReceivingHandlers } = require('./stockReceiving')
const { reserveBusinessReferences, createBusinessReferenceHandler } = require('./businessReferences')

describe('approved operations revision — isolated emulator', { skip: process.env.RUN_OPERATIONS_REVISION_TESTS !== 'true' }, () => {
  if (process.env.FIRESTORE_EMULATOR_HOST !== '127.0.0.1:8080') throw new Error('Exact loopback emulator required')
  const { initializeApp, deleteApp } = require('firebase-admin/app')
  const { getFirestore } = require('firebase-admin/firestore')
  const project = 'demo-operations-revision', app = initializeApp({ projectId: project }, 'operations-revision'), db = getFirestore(app)
  const ops = createFinanceOperations(db, () => Date.parse('2026-10-29T09:00:00Z')), register = createRegisterHandlers(ops), decisions = createVendorDecisionHandlers(ops, register)
  const receiving = createStockReceivingHandlers(db, () => '2026-10-29T09:00:00.000Z')
  const req = (data, uid = 'owner') => ({ auth: { uid, token: { auth_time: 42 } }, data: { operationId: randomUUID(), ...data } })
  const base = 'posSandboxes/test/'
  const read = async path => (await db.doc(path).get()).data()
  async function saveAndDispatch(quantity = 1) {
    const id = randomUUID(), product = await read(`${base}products/p`), receipt = await read(`${base}goodsReceipts/grn-source`), saved = await opsReturn.save(req({ id, expectedRevision: 0, vendorId: 'v', date: '2026-10-29', reason: 'Damaged goods returned', lines: [{ productId: 'p', sourceReceiptId: 'grn-source', quantity, expectedProductRevision: product.revision, expectedReceiptRevision: receipt.revision, unitCostPaise: 200 }] }))
    const dispatched = await opsReturn.dispatch(req({ id, expectedRevision: saved.revision }))
    return { id, saved, dispatched }
  }
  const opsReturn = require('./vendorStockReturns').createVendorStockReturnHandlers(ops, register)
  const resolveReferences = createBusinessReferenceHandler(db)
  beforeEach(async () => {
    // Clear only this dedicated demo emulator project; no production endpoint is used.
    for (const collection of await db.listCollections()) await db.recursiveDelete(collection)
    const b = db.batch()
    for (const [uid, role] of [['owner', 'owner'], ['manager', 'manager'], ['billing', 'billing'], ['stranger', 'billing']]) b.set(db.doc(`users/${uid}`), { name: `Synthetic ${uid}`, role, approvalStatus: 'approved', disabled: false })
    b.set(db.doc('appMetadata/vendorLedgerV2Config'), { enabled: true, activationDate: '2026-01-01' })
    b.set(db.doc('vendorsV2/v'), { id: 'v', canonicalName: 'Synthetic Vendor', active: true, revision: 1, aliases: [], suppliedBrands: [], openingBalancePaise: 0 })
    b.set(db.doc('vendorAccountStatesV2/v'), { id: 'v', vendorId: 'v', outstandingPaise: 2000, vendorCreditPaise: 0, revision: 1 })
    b.set(db.doc('purchasesV2/purchase'), { id: 'purchase', vendorId: 'v', invoiceNumber: 'INV-SYNTHETIC', invoiceDate: '2026-10-29', invoiceTotalPaise: 2000, revision: 1 })
    b.set(db.doc('invoiceStatesV2/purchase'), { id: 'purchase', invoiceId: 'purchase', vendorId: 'v', openAmountPaise: 2000, reservedAmountPaise: 0, revision: 1 })
    b.set(db.doc(`${base}products/p`), { id: 'p', barcode: '000000000001', name: 'Synthetic Product', active: true, currentQuantity: 10, revision: 1, sellingPricePaise: 300 })
    b.set(db.doc(`${base}goodsReceipts/grn-source`), { id: 'grn-source', status: 'submitted', vendorId: 'v', vendorName: 'Synthetic Vendor', invoiceNumber: 'INV-SYNTHETIC', invoiceDate: '2026-10-29', receiptDate: '2026-10-29', payablePurchaseId: 'purchase', revision: 1, lines: [{ productId: 'p', barcode: '000000000001', productName: 'Synthetic Product', quantity: 10, unitCostPaise: 200, lineTotalPaise: 2000 }] })
    await b.commit()
  })
  after(() => deleteApp(app))

  it('assigns concurrent permanent per-type references without reusing a deleted alias', async () => {
    const reserve = (prefix, id) => db.runTransaction(async tx => { const result = await reserveBusinessReferences(tx, db, [{ prefix, id }], 'owner', '2026-10-29T09:00:00.000Z'); result.writes.forEach(write => write()); return result.result[0].reference })
    const [a, b] = await Promise.all([reserve('GRN', 'one'), reserve('GRN', 'two')])
    assert.deepEqual([a, b].sort(), ['GRN0001', 'GRN0002'])
    await db.doc(`businessReferences/${require('./stockOperations').hash('GRN:one')}`).delete()
    assert.equal(await reserve('GRN', 'one'), 'GRN0003')
    await db.doc('businessReferenceCounters/GRN').set({ lastNumber: 9999 })
    assert.equal(await reserve('GRN', 'after-9999'), 'GRN10000')
    assert.equal(await reserve('AUDIT', 'one'), 'AUDIT0001')
  })

  it('resolves only existing authorized records and never trusts a client-supplied reference', async () => {
    const result = await resolveReferences({ auth: { uid: 'billing' }, data: { requests: [{ prefix: 'PRODUCT', id: 'p' }, { prefix: 'PRODUCT', id: 'forged' }] } })
    assert.deepEqual(result, [{ prefix: 'PRODUCT', id: 'p', reference: 'PRODUCT0001' }])
    await assert.rejects(resolveReferences({ auth: { uid: 'stranger' }, data: { requests: [{ prefix: 'NOTREAL', id: 'x' }] } }), /Invalid business reference/)
    await db.doc('loans/private-loan').set({ id: 'private-loan' })
    assert.deepEqual(await resolveReferences({ auth: { uid: 'billing' }, data: { requests: [{ prefix: 'LOAN', id: 'private-loan' }] } }), [])
    assert.equal((await resolveReferences({ auth: { uid: 'owner' }, data: { requests: [{ prefix: 'LOAN', id: 'private-loan' }] } }))[0].reference, 'LOAN0001')
  })

  it('saves a non-posting return draft, then deducts stock exactly once at dispatch', async () => {
    const id = randomUUID(), draft = await opsReturn.save(req({ id, expectedRevision: 0, vendorId: 'v', date: '2026-10-29', reason: 'Damaged goods returned', lines: [{ productId: 'p', sourceReceiptId: 'grn-source', quantity: 2, expectedProductRevision: 1, expectedReceiptRevision: 1, unitCostPaise: 200 }] }))
    assert.match(draft.reference, /^RETURN\d{4,}$/)
    assert.equal((await read(`${base}products/p`)).currentQuantity, 10)
    assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise, 2000)
    await assert.rejects(opsReturn.dispatch(req({ id, expectedRevision: draft.revision }, 'manager')), /creator or owner/)
    const operation = req({ id, expectedRevision: draft.revision })
    const dispatched = await opsReturn.dispatch(operation)
    assert.equal((await read(`${base}products/p`)).currentQuantity, 8)
    assert.equal(dispatched.outcome, 'pending')
    assert.equal((await db.collection(`${base}stockMovements`).where('vendorReturnId', '==', id).get()).size, 1)
    assert.deepEqual(await opsReturn.dispatch(operation), dispatched)
    await assert.rejects(opsReturn.dispatch(req({ id, expectedRevision: dispatched.revision })), /already been dispatched/)
    assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise, 2000)
  })

  it('records a credit note against the invoice once without a second stock movement', async () => {
    const { id, dispatched } = await saveAndDispatch(1)
    const decision = req({ returnId: id, expectedRevision: dispatched.revision, outcome: 'vendor-credit', creditedValuePaise: 200, creditNoteNumber: 'CN-SYN-1', creditNoteDate: '2026-10-29', outcomeReason: 'Credit note received and checked' })
    const result = await decisions.resolveReturn(decision)
    assert.equal(result.creditedValuePaise, 200)
    assert.equal((await read('invoiceStatesV2/purchase')).openAmountPaise, 1800)
    assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise, 1800)
    assert.equal((await db.collection(`${base}stockMovements`).where('vendorReturnId', '==', id).get()).size, 1)
    assert.deepEqual(await decisions.resolveReturn(decision), result)
    const second = await saveAndDispatch(1)
    await assert.rejects(decisions.resolveReturn(req({ returnId: second.id, expectedRevision: second.dispatched.revision, outcome: 'vendor-credit', creditedValuePaise: 200, creditNoteNumber: 'cn-syn-1', creditNoteDate: '2026-10-29', outcomeReason: 'Duplicate credit note' })), /already been applied/i)
    assert.equal((await read('invoiceStatesV2/purchase')).openAmountPaise, 1800)
  })

  it('receives replacement and rejected goods as linked zero-payable GRNs exactly once', async () => {
    const { id, dispatched } = await saveAndDispatch(1)
    const agreement = await decisions.resolveReturn(req({ returnId: id, expectedRevision: dispatched.revision, outcome: 'replacement', outcomeReason: 'Replacement agreed with supplier' }))
    const received = await opsReturn.receive(req({ id, expectedRevision: agreement.revision, date: '2026-10-29', lines: [{ productId: 'p', quantity: 1, expectedRevision: 2 }] }))
    assert.match(received.reference, /^GRN\d{4,}$/)
    assert.equal((await read(`${base}products/p`)).currentQuantity, 10)
    const receipt = await read(`${base}goodsReceipts/${received.receiptId}`)
    assert.equal(receipt.invoiceTotalPaise, 0)
    assert.equal(receipt.payablePurchaseId, undefined)
    assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise, 2000)
    await assert.rejects(opsReturn.receive(req({ id, expectedRevision: received.return.revision, date: '2026-10-29', lines: [{ productId: 'p', quantity: 1, expectedRevision: 3 }] })), /not awaiting physical receipt/)
  })

  it('restores rejected goods physically received and releases the original GRN return capacity', async () => {
    const { id, dispatched } = await saveAndDispatch(10)
    assert.equal((await read(`${base}products/p`)).currentQuantity, 0)
    const rejected = await decisions.resolveReturn(req({ returnId: id, expectedRevision: dispatched.revision, outcome: 'rejected', outcomeReason: 'Supplier rejected this return' }))
    const received = await opsReturn.receive(req({ id, expectedRevision: rejected.revision, date: '2026-10-29', lines: [{ productId: 'p', quantity: 10, expectedRevision: 2 }] }))
    assert.equal((await read(`${base}products/p`)).currentQuantity, 10)
    assert.equal((await read(`vendorReturnReceiptStates/${require('./stockOperations').hash('grn-source:p')}`)).returnedQuantity, 0)
    const next = await opsReturn.save(req({ id: randomUUID(), expectedRevision: 0, vendorId: 'v', date: '2026-10-29', reason: 'A second vendor return', lines: [{ productId: 'p', sourceReceiptId: 'grn-source', quantity: 10, expectedProductRevision: 3, expectedReceiptRevision: 1, unitCostPaise: 200 }] }))
    assert.equal(next.quantity, 10)
    assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise, 2000)
    assert.equal(received.return.stockStatus, 'returned-back')
  })

  it('blocks reversing a GRN after a linked vendor return was dispatched', async () => {
    const capacityId = require('./stockOperations').hash('grn-source:p')
    await db.doc(`vendorReturnReceiptStates/${capacityId}`).set({ sourceReceiptId: 'grn-source', productId: 'p', returnedQuantity: 1 })
    await assert.rejects(receiving.previewReverse({ auth: { uid: 'owner' }, data: { id: 'grn-source' } }), /dispatched vendor returns/)
    assert.equal((await read(`${base}goodsReceipts/grn-source`)).status, 'submitted')
    assert.equal((await read(`${base}products/p`)).currentQuantity, 10)
    assert.equal((await read('vendorAccountStatesV2/v')).outstandingPaise, 2000)
  })
})
