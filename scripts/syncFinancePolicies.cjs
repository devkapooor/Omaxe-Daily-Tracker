// Generate server policy copies from the existing pure domain contracts.
// No browser SDK or app state is included in the server runtime.
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
for (const [source, target] of [['src/domain/vendorLedgerV2.ts', 'functions/vendorLedgerPolicy.js'], ['src/domain/cashoutCorrections.ts', 'functions/cashoutPolicy.js']]) {
  const text = fs.readFileSync(path.join(root, source), 'utf8')
  const output = ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText
  const header = '// Generated by scripts/syncFinancePolicies.cjs from ' + source + '\n// SHA256 ' + crypto.createHash('sha256').update(text).digest('hex') + '\n'
  fs.writeFileSync(path.join(root, target), header + output)
}
